// Función para determinar toxicidad basada en DL50
export function determinarToxicidad(dl50Contacto: number): ToxicidadAbejas {
  if (dl50Contacto < 2) return 'muy_tóxico';
  if (dl50Contacto < 11) return 'tóxico';
  if (dl50Contacto <= 25) return 'moderadamente_tóxico';
  return 'prácticamente_no_tóxico';
}
